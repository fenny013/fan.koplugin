local I18n = { strings = { ru = ru } }

function I18n.language()
    local language = G_reader_settings and G_reader_settings:readSetting("language")
    language = language or GetText.current_lang or os.getenv("LANG") or "en"
    return language:lower():match("^ru") and "ru" or "en"
end

function I18n.t(text)
    if I18n.language() == "ru" then return ru[text] or text end
    return text
end

return I18n
